/**
 * THE ROSTER: the one list of playable titans, in the order the menus show them. Everything that walks "every titan" derives
 * from it: `TITAN_IDS` (plus the locked boss, the Mouth), `SLICE.titans`, `IMPLEMENTED_TITANS`, the site's titan cards, the
 * press cards, the data-driven roster checks (src/titans/roster.test.ts).
 *
 * `npm run new:titan -- <id> "<English Name>" "<Korean name>"` adds a new id here, above the `new:titan` marker, and
 * registers the titan's own files (src/titans/kit/<id>/, src/combat/behaviours/kit/<id>.ts). See docs/TITAN_GUIDE.md.
 *
 * D36: 'colossus' is the big-eye colossus, displayed as The Last One; 'lastone' is the tendril titan, displayed as The Witness.
 */
export const ROSTER_IDS = [
  'colossus',
  'lastone',
  'asteroid',
  'nexus',
  'blackhole',
  'supernova',
  'planet',
  'uri',
  'cradle',
  'cradlechild',
  'remainder',
  // new:titan (the scaffold adds new ids above this line)
] as const;

export type RosterId = (typeof ROSTER_IDS)[number];

/**
 * Size classes: the largest dimension (px, at game size) a titan of that class spans. The roster checks hold every titan to
 * its class and to the arena (src/titans/roster.test.ts).
 */
export type SizeClass = 'small' | 'medium' | 'large' | 'huge';
export const SIZE_CLASSES: Readonly<Record<SizeClass, readonly [number, number]>> = {
  small: [80, 135],
  medium: [110, 190],
  large: [150, 250],
  huge: [180, 320],
};

/**
 * Titan kinds: what a titan fundamentally IS, for authoring. A kind is a family of looks, materials, motion and sound, not a
 * gameplay type: matchups still come only from damage types against material `resist`. The titan builder and
 * `npm run new:titan -- --kind=<kind>` start a new titan from its kind's preset (src/titans/kit/kinds.ts).
 */
export const TITAN_KINDS = ['celestial', 'mineral', 'organic', 'construct', 'cosmic'] as const;
export type TitanKind = (typeof TITAN_KINDS)[number];

/** A titan's default strength tier when its roster data does not give one (COSMIC CLASH's order). */
export const TIER_OF_SIZE: Readonly<Record<SizeClass, number>> = { small: 1, medium: 2, large: 3, huge: 4 };

/** How long a newly shipped titan wears the NEW tag in the COSMIC CLASH lineup (days after `shippedAt`). */
export const NEW_TITAN_DAYS = 28;

/** A catalogue number as the Observatory shows it: 9 → "ADK-009". */
export const catalogueId = (n: number): string => `ADK-${String(n).padStart(3, '0')}`;

/** A titan's card on the landing page (site/index.html, generated by tools/site/roster.ts) and its press card. */
export interface SiteCard {
  /** File stem of its media: site/media/titans/<file>.png, <file>-loop.{webm,mp4}, site/media/type/ko-<file>.png. */
  file: string;
  /** The one idea it is ("gravity", "possession"). */
  essence: string;
  name: string;
  ko: string;
  /** Optional quoted tagline under the Korean name. */
  tag?: string;
  /** One or two sentences of lore. */
  lore: string;
  /** How it destroys matter: a bold word and one sentence. */
  mech: { title: string; text: string };
  accent: string;
  accent2: string;
  /** How the card scales the portrait: x1 (as is, up to the card), x2 (small bodies at ×2), half (a big painted sprite). */
  portrait: 'x1' | 'x2' | 'half';
  /** A hover clip exists (site/media/titans/<file>-loop.webm/.mp4; `npm run site:media titans`). */
  clip: boolean;
  /** The card's aria label when not "<name>: play its clip". */
  aria?: string;
}

/** A bright body lights the scenery and the other sprite (src/app/fx.ts): [r,g,b] 0..1, falloff radius px, intensity. */
export interface TitanLight {
  c: [number, number, number];
  radius: number;
  base: number;
}

/** A kit titan's voice tuning (src/audio/voices/kitVoice.ts): every number 0..1 except the pitch. */
export interface KitVoiceTuning {
  /** The body's fundamental, Hz (30 = a mountain, 120 = a boulder). Keep it low: epic, cosmic (D34). */
  pitch: number;
  /** 0 = smooth (a bell, a star), 1 = gritty (rock, rust). */
  grit: number;
  /** 0 = dead thud, 1 = it rings like a struck bell when hit. */
  ring: number;
  /** Reverb: 0 = close, 1 = a cathedral. */
  wet: number;
}

/** The roster data of a titan built with the kit (`npm run new:titan`): lives in its JSON, as `kit`. */
/**
 * One animation preset (`kit.motion`): its `type`, the `material` (key) whose cells it moves, when it runs (`on`: 'always' or a
 * move slot; absent = its type's default) and its knobs (numbers; absent = defaults). Iris also takes `cover`: the material
 * whose colours its petals use.
 */
export interface MotionPreset {
  type: string;
  material: string;
  on?: string;
  [knob: string]: number | string | undefined;
}

export interface TitanKit {
  /** Which template it was scaffolded from: 'blob' or an existing titan's id (its painter and behaviour). */
  template: string;
  /** What it is (celestial, mineral, organic, construct, cosmic): its authoring family, `TITAN_KINDS`. */
  kind?: TitanKind;
  /**
   * 'image': its body was imported from key art in the titan builder (body.json in its folder, painted by
   * src/titans/kit/image.ts) instead of being painted by its template's painter. Its behaviour is still the template's.
   */
  painter?: 'image';
  size: SizeClass;
  /** Its home stage (StageId): the ladder rung and showcase fights use it. */
  stage: string;
  light?: TitanLight;
  voice?: KitVoiceTuning;
  site: SiteCard;
  /**
   * Animation presets (src/combat/behaviours/kit/motion.ts): living-idle and move-animation pieces bound to one material each
   * (swirl, pulse, shimmer, stretch, iris), tuned with sliders in the titan builder. A titan with a hand-written idle ignores
   * them.
   */
  motion?: MotionPreset[];
  /** Homage notes (what it nods to, and how it stays its own), for the director. Not shown in the game. */
  homage?: string;
  /**
   * Strength tier, 1 (light: an opener) to 5 (the Last One): COSMIC CLASH opens on the tier-1 titans. Absent = from its size
   * class (`TIER_OF_SIZE`).
   */
  tier?: number;
  /** The day it shipped (YYYY-MM-DD), stamped by `npm run titan:ship`: COSMIC CLASH tags it NEW for `NEW_TITAN_DAYS`. */
  shippedAt?: string;
  /** Its catalogue number in arrival order (9 = ADK-009), stamped by `npm run titan:ship`: see `catalogueId`. */
  catalogue?: number;
  /**
   * Work in progress: it stays on the roster (every check covers it) but is kept out of the menus, the site cards, the press
   * kit and the site's titan count until WJ ships it. Unlock it in the menus with `?wip=<id>` (or `?wip=all`, or `?<id>=1`).
   */
  wip?: boolean;
}
