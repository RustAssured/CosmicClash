/**
 * The roster's presentation data, one entry per roster titan (src/contracts/roster.ts), in roster order: its size class, home
 * stage and its landing-page / press card. The site (tools/site/roster.ts), the press cards and key art, the site art and
 * matter counters and the roster checks (roster.test.ts, `npm run titan:check`) all read this.
 *
 * The titans that predate the kit keep their entry in BUILTIN below (their JSON is generated by authoring tools, so it
 * does not carry it); a kit titan carries its own in its JSON as `kit` (src/titans/kit/<id>/<id>.json).
 */
export interface RosterEntry {
  id: TitanId;
  size: SizeClass;
  /** Home stage (StageId). */
  stage: string;
  /** Game px per portrait px (우리's portrait is drawn in its asset's reference space). */
  portraitScale: number;
  /** Optional body light (src/app/fx.ts); the titans before the kit have theirs in fx.ts. */
  light?: TitanLight;
  site: SiteCard;
  /** Built with the kit (its JSON carries this entry). */
  kit: boolean;
  /** Work in progress (its JSON's `kit.wip`): kept out of the menus, site and press until it ships. */
  wip?: boolean;
  /** Strength tier 1–5 (COSMIC CLASH opens on the tier-1 titans; the Last One is 5). */
  tier: number;
  /** The day it shipped (YYYY-MM-DD): the NEW tag in the COSMIC CLASH lineup. Absent while it is WIP. */
  shippedAt?: string;
  /** Catalogue number in arrival order (ADK-001 …; `catalogueId`), for the site's Observatory. Absent while it is WIP. */
  catalogue?: number;
}

type Builtin = Omit<RosterEntry, 'id' | 'kit'>;

