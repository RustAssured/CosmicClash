/** The order the site shows the cards in (the landing page's order: the Witness and 우리 last). Kit titans follow. */
const SITE_ORDER: readonly string[] = [
  'colossus',
  'planet',
  'asteroid',
  'nexus',
  'blackhole',
  'supernova',
  'lastone',
  'uri',
];

function entryOf(id: TitanId): RosterEntry {
  const b = BUILTIN[id];
  if (b) return { id, kit: false, ...b };
  const k = kitTitan(id)?.def.kit ?? getTitanDef(id).kit;
  if (!k)
    throw new Error(
      `roster: titan '${id}' has no roster entry (BUILTIN in src/titans/roster.ts or its JSON kit block)`,
    );
  return {
    id,
    kit: true,
    size: k.size,
    stage: k.stage,
    portraitScale: 1,
    light: k.light,
    site: k.site,
    ...(k.wip ? { wip: true } : {}),
    tier: k.tier ?? TIER_OF_SIZE[k.size],
    ...(k.shippedAt ? { shippedAt: k.shippedAt } : {}),
    ...(k.catalogue ? { catalogue: k.catalogue } : {}),
  };
}

/**
 * What the tournament needs of the roster (src/ui/ladder.ts `LadderTitan`): every titan's id, tier, home stage, ship date,
 * catalogue number and WIP flag. The app hands this to the UI; COSMIC CLASH builds its lineup from it.
 */
export const ladderRoster = (): {
  id: TitanId;
  tier: number;
  shippedAt?: string;
  catalogue?: number;
  wip?: boolean;
  stage?: string;
}[] =>
  ROSTER.map((r) => ({
    id: r.id,
    tier: r.tier,
    stage: r.stage,
    ...(r.shippedAt ? { shippedAt: r.shippedAt } : {}),
    ...(r.catalogue ? { catalogue: r.catalogue } : {}),
    ...(r.wip ? { wip: true } : {}),
  }));

/** Every roster titan's entry, in roster order. */
export const ROSTER: readonly RosterEntry[] = ROSTER_IDS.map((id) => entryOf(id));

/** The roster in the landing page's card order. Work-in-progress titans (`kit.wip`) are left out until they ship. */
export const SITE_ROSTER: readonly RosterEntry[] = [
  ...SITE_ORDER.map((id) => ROSTER.find((r) => r.id === id)).filter((r): r is RosterEntry => !!r),
  ...ROSTER.filter((r) => !SITE_ORDER.includes(r.id)),
].filter((r) => !r.wip);

/** The work-in-progress titans (on the roster, kept out of the menus, site and press until WJ ships them). */
export const WIP_IDS: readonly TitanId[] = ROSTER.filter((r) => r.wip).map((r) => r.id);

/**
 * Is a work-in-progress titan unlocked in the menus for this session? Only by the URL: `?wip=<id>[,<id>…]`, `?wip=all` or
 * `?<id>=1` (WJ's test builds). Headless code (tests, tools) sees every WIP titan locked. Shipped titans are always offered.
 */
export function isTitanOffered(id: TitanId): boolean {
  if (!WIP_IDS.includes(id)) return true;
  const q = new URLSearchParams(globalThis.location?.search ?? '');
  const wip = (q.get('wip') ?? '').split(',');
  return wip.includes('all') || wip.includes(id) || q.get(id) === '1';
}

export const rosterEntry = (id: TitanId): RosterEntry | undefined => ROSTER.find((r) => r.id === id);

/** A size class's span (largest dimension, game px). */
export const sizeRange = (s: SizeClass): readonly [number, number] => SIZE_CLASSES[s];
